"""Loader for the synthetic capability corpora.

The generated data is **repo-only and gitignored** (``eval/synthetic/``): it is regenerated by
running the generator, never committed and never shipped in the wheel. So the loader has to answer
"where is it?" without assuming it exists, and fail with an instruction rather than a traceback.

Resolution order for the corpus root:

1. ``$PERCEPT_SYNTHETIC_DIR`` — an explicit override (what tests use for a tmp dir).
2. ``<repo root>/eval/synthetic`` — found by walking up from this file for a directory that has both
   ``eval/`` and ``packages/``.
"""

from __future__ import annotations

import json
import os
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Iterator

from .schema import CORPUS_NAMES, ValidationError, validate_corpus

__all__ = ["Corpus", "Case", "synthetic_root", "corpus_dir", "load_corpus", "load_all", "available"]

_ENV = "PERCEPT_SYNTHETIC_DIR"


class CorpusMissing(FileNotFoundError):
    """The corpus has not been generated. Raised with the exact command that fixes it."""


@dataclass(frozen=True)
class Case:
    """One labelled case: the input steps, and the EXPECTED ANSWER."""

    id: str
    description: str
    steps: list[dict]
    expect: dict[str, Any]
    proves: str
    does_not_prove: str
    stream: dict[str, Any]
    label: dict[str, Any]

    @property
    def verdicts(self) -> list[dict]:
        """The per-step scripted verdict blocks — feed to ``ScriptedJudge.from_steps``."""
        return [s.get("verdict") or {} for s in self.steps]


@dataclass(frozen=True)
class Corpus:
    """A loaded, validated corpus."""

    name: str
    kind: str
    stream: dict[str, Any]
    labels: dict[str, Any]
    cases: tuple[Case, ...]

    def case(self, case_id: str) -> Case:
        for c in self.cases:
            if c.id == case_id:
                return c
        raise KeyError(f"{self.name}: no case {case_id!r} (have {[c.id for c in self.cases]})")

    def __iter__(self) -> Iterator[Case]:
        return iter(self.cases)

    def __len__(self) -> int:
        return len(self.cases)


def synthetic_root() -> Path:
    """The directory holding the generated corpora (may not exist yet)."""
    override = os.environ.get(_ENV)
    if override:
        return Path(override)
    here = Path(__file__).resolve()
    for parent in here.parents:
        if (parent / "eval").is_dir() and (parent / "packages").is_dir():
            return parent / "eval" / "synthetic"
    # Installed from a wheel with no repo around it: there is nowhere to look.
    return Path.cwd() / "eval" / "synthetic"


def corpus_dir(name: str, root: "Path | str | None" = None) -> Path:
    return Path(root) / name if root else synthetic_root() / name


def available(root: "Path | str | None" = None) -> list[str]:
    """Corpus names that are present on disk right now."""
    base = Path(root) if root else synthetic_root()
    return [n for n in CORPUS_NAMES if (base / n / "stream.json").is_file()]


def load_corpus(name: str, root: "Path | str | None" = None, *, validate: bool = True) -> Corpus:
    """Load + validate one corpus. Raises :class:`CorpusMissing` with the fix if it is not generated."""
    if name not in CORPUS_NAMES:
        raise KeyError(f"unknown corpus {name!r} (have {list(CORPUS_NAMES)})")
    d = corpus_dir(name, root)
    stream_p, labels_p = d / "stream.json", d / "labels.json"
    if not stream_p.is_file() or not labels_p.is_file():
        raise CorpusMissing(
            f"synthetic corpus {name!r} not generated at {d} — the data is gitignored by design. "
            f"Run:  python3 -m percept.harness.synthetic.generate"
        )
    stream = json.loads(stream_p.read_text(encoding="utf-8"))
    labels = json.loads(labels_p.read_text(encoding="utf-8"))
    if validate:
        validate_corpus(name, stream, labels)

    by_id = {c["id"]: c for c in labels["cases"]}
    cases = tuple(
        Case(
            id=c["id"],
            description=c["description"],
            steps=list(c["steps"]),
            expect=dict(by_id[c["id"]]["expect"]),
            proves=by_id[c["id"]]["proves"],
            does_not_prove=by_id[c["id"]]["does_not_prove"],
            stream=c,
            label=by_id[c["id"]],
        )
        for c in stream["cases"]
    )
    return Corpus(name=name, kind=stream["kind"], stream=stream, labels=labels, cases=cases)


def load_all(root: "Path | str | None" = None, *, validate: bool = True) -> dict[str, Corpus]:
    """Load every corpus. Raises if any is missing — the whole set is generated together."""
    return {n: load_corpus(n, root, validate=validate) for n in CORPUS_NAMES}


__all__.append("CorpusMissing")
__all__.append("ValidationError")
